defined('COT_CODE') or die('Wrong URL');

$htmlpurifier_preset = [

    /* ========================================================================
     * БЛОК 1. ОРИГИНАЛЬНЫЕ НАСТРОЙКИ — ОСТАВЛЕНЫ КАК ЕСТЬ
     * ========================================================================
     * Ниже — то, что было в файле изначально. Не меняем, чтобы не сломать
     * поведение резервного пресета для групп, у которых нет своего файла.
     * ---------------------------------------------------------------------- */

    // === Автоформатирование ===
    'AutoFormat.AutoParagraph'                => false,
    'AutoFormat.DisplayLinkURI'               => false,
    'AutoFormat.Linkify'                      => false,
    'AutoFormat.RemoveEmpty.RemoveNbsp'       => false,
    'AutoFormat.RemoveEmpty'                  => true,
    'AutoFormat.RemoveSpansWithoutAttributes' => true,

    // === Пользовательские фильтры ===
    'Filter.Custom'                           => [],

    // === HTML и вывод ===
    // null = политика HTML Purifier по умолчанию.
    // Перезаписывается в Блоке 2 жёстким whitelist.
    'HTML.Allowed'                            => null,

    'HTML.FlashAllowFullScreen'               => false,
    'HTML.SafeObject'                         => true,

    // === Режим доверия ===
    // false = полный набор фильтров Purifier. Для пользовательского
    // контента (комментарии, форум, гостевые страницы) это единственно
    // правильное значение.
    'HTML.Trusted'                            => false,

    'Output.FlashCompat'                      => true,

    // === URI ===
    'URI.DisableExternal'                     => false,
    'URI.DisableExternalResources'            => false,


    /* ========================================================================
     * БЛОК 2. ДОБАВЛЕНО: ЯВНЫЙ WHITELIST ТЕГОВ
     * ========================================================================
     * Всё, что НЕ перечислено, будет вырезано — включая <script>, <iframe>,
     * <style>, <form>, <object>, <svg> и любые другие опасные теги.
     *
     * Даже если HTML.Trusted по ошибке станет true, этот whitelist
     * продолжит держать оборону.
     *
     * Плейсхолдеры (p, div, span, h1–h6, ul, li и т.д.) — базовый набор,
     * который выдают Markdown-парсеры вроде Parsedown.
     * ---------------------------------------------------------------------- */
    'HTML.Allowed'                            =>
          // Абзацы, переносы, контейнеры
          'p[align|style|class],'
        . 'br,'
        . 'div[align|class|style|id],'
        . 'span[class|style],'

        // Инлайн-форматирование — то, что реально генерит Parsedown
        . 'strong,b,em,i,u,s,strike,del,ins,sup,sub,small,big,'

        // Ссылки и картинки
        . 'a[href|title|rel|target|class],'
        . 'img[src|alt|title|width|height|class|style],'

        // Списки
        . 'ul[class|style],ol[class|style],li[class|style],'

        // Цитаты и код
        . 'blockquote[class|style|cite],'
        . 'pre[class|style],code[class|style],'

        // Заголовки H1..H6
        . 'h1[class|style|id],h2[class|style|id],h3[class|style|id],'
        . 'h4[class|style|id],h5[class|style|id],h6[class|style|id],'

        // Таблицы (Parsedown их генерит)
        . 'table[class|style|border|cellpadding|cellspacing],'
        . 'thead[class],tbody[class],tfoot[class],'
        . 'tr[class|style],'
        . 'th[class|style|colspan|rowspan],'
        . 'td[class|style|colspan|rowspan],'

        // Разделитель и расширенные безопасные теги
        . 'hr[class|style],'
        . 'kbd,mark,abbr[title],cite,figure,figcaption,details,summary',


    /* ========================================================================
     * БЛОК 3. ДОБАВЛЕНО: ЧЁРНЫЙ СПИСОК ТЕГОВ — ВТОРОЙ СЛОЙ ЗАЩИТЫ
     * ========================================================================
     * Срабатывает даже если whitelist из Блока 2 по какой-то причине
     * пропустит опасный тег. Здесь всё, чем атакуют посетителей и сайт.
     * ---------------------------------------------------------------------- */
    'HTML.ForbiddenElements'                  => [

        // Исполняемый JavaScript — прямая XSS
        'script',

        // Подмена вёрстки сайта
        'style',        // <style>body{display:none}</style>
        'link',         // загрузка чужого CSS/JS
        'meta',         // <meta http-equiv="refresh"> — авторедирект
        'base',         // <base href="//evil.example"> — угон ссылок

        // Подмена форм — фишинг и CSRF
        'form',
        'input',
        'textarea',
        'select',
        'option',
        'button',

        // Внешние встраивания — сюда попадает
        // <iframe src="/admin.php"> и <iframe src="//evil.example">
        'iframe',
        'object',
        'embed',
        'applet',

        // Небезопасный рендеринг и XSS-векторы
        'canvas',       // canvas скриптуется
        'svg',          // <svg><script>alert(1)</script></svg>
        'math',         // исторически использовался для XSS
    ],


    /* ========================================================================
     * БЛОК 4. ДОБАВЛЕНО: ЧЁРНЫЙ СПИСОК АТРИБУТОВ — ТРЕТИЙ СЛОЙ ЗАЩИТЫ
     * ========================================================================
     * '*@on*' = любой атрибут, начинающийся с "on", у любого тега:
     * onclick, onerror, onload, onmouseover, onfocus, onwheel,
     * onanimationend и сотни других. Это критично для XSS.
     * ---------------------------------------------------------------------- */
    'HTML.ForbiddenAttributes'                => [
        '*@on*',         // все обработчики событий
        '*@formaction',  // переопределение action формы
        '*@xmlns',       // ломает XHTML-парсинг
        '*@srcdoc',      // встраивание произвольного HTML в iframe
        'a@ping',        // трекинг-пинг браузера при клике
        'a@download',    // принудительное скачивание файла
    ],


    /* ========================================================================
     * БЛОК 5. ДОБАВЛЕНО: WHITELIST СХЕМ ССЫЛОК
     * ========================================================================
     * Отсекает javascript:, vbscript:, data:text/html, file:, chrome:,
     * about: и прочую экзотику. Оставляем только безопасные схемы.
     * ---------------------------------------------------------------------- */
    'URI.AllowedSchemes'                      => [
        'http'   => true,
        'https'  => true,
        'mailto' => true,
        'tel'    => true,
    ],


    /* ========================================================================
     * БЛОК 6. ДОБАВЛЕНО: WHITELIST ДЛЯ IFRAME (СТРАХОВКА)
     * ========================================================================
     * Тег <iframe> уже вырезан в Блоке 3. Эта опция оставлена как
     * дополнительный слой: если кто-то в будущем уберёт iframe из
     * ForbiddenElements, regexp ограничит источники YouTube / Vimeo / VK.
     * ---------------------------------------------------------------------- */
    'HTML.SafeIframe'                         => true,
    'URI.SafeIframeRegexp'                    => '%^(https?:)?//('
        . 'www\.youtube(?:-nocookie)?\.com/embed/|'
        . 'player\.vimeo\.com/video/|'
        . 'vk\.com/video_ext\.php'
        . ')%i',


    /* ========================================================================
     * БЛОК 7. ДОБАВЛЕНО: КОНТРОЛЬ АТРИБУТОВ target / rel / id / class
     * ========================================================================
     * Урезаем возможности пользователя влиять на поведение ссылок
     * и вмешиваться в системные id.
     * ---------------------------------------------------------------------- */
    // target у ссылок: только открытие в новой вкладке.
    'Attr.AllowedFrameTargets'                => ['_blank'],

    // rel: только безопасные значения.
    'Attr.AllowedRel'                         => ['nofollow', 'noreferrer', 'noopener'],

    // id запрещён — иначе пользователь создаст якорь с системным id
    // и сломает вёрстку или JS-код сайта.
    'Attr.EnableID'                           => false,

    // class разрешён (нужен для подсветки кода, таблиц и т.п.).
    // Реально применяется только к тегам из Блока 2.
    'Attr.AllowedClasses'                     => null,


    /* ========================================================================
     * БЛОК 8. ДОБАВЛЕНО: ВЫКЛЮЧЕНИЕ FLASH / OBJECT / EMBED
     * ========================================================================
     * Устаревшие технологии встраивания — прямой путь для XSS и
     * загрузки чужого SWF. Для обычных пользователей не нужны.
     * ---------------------------------------------------------------------- */
    'HTML.FlashAllowFullScreen'               => false,
    'HTML.SafeObject'                         => false,
    'HTML.SafeEmbed'                          => false,
    'Output.FlashCompat'                      => false,


    /* ========================================================================
     * БЛОК 9. СОВМЕСТИМОСТЬ С PARSEDOWN
     * ========================================================================
     * Если Cotonti используется с парсером `parsedown`, порядок такой:
     *
     *  1. Пользователь пишет Markdown.
     *  2. Parsedown превращает Markdown в HTML — это происходит ДО
     *     HTML Purifier и происходит на выводе (cot_parse()).
     *  3. HTML Purifier фильтрует полученный HTML по этому пресету.
     *
     * Что важно:
     *  • Список HTML.Allowed (Блок 2) должен включать ВСЕ теги,
     *    которые генерит Parsedown: p, br, strong, em, del (для ~~),
     *    a, img, ul, ol, li, blockquote, pre, code, h1..h6, hr,
     *    table/thead/tbody/tr/th/td. Иначе Purifier вырежет их
     *    и верстка развалится.
     *
     *  • Parsedown не генерит <script>, <iframe>, <style>, <form>,
     *    <object>, <svg>, <math> — эти теги вырезаются в Блоке 3,
     *    конфликтов с Parsedown нет.
     *
     *  • Parsedown может генерить <img src="..."> — src проходит
     *    через URI.AllowedSchemes (Блок 5). Если нужно разрешить
     *    data:image/* для инлайн-картинок — добавь:
     *        'data' => true,
     *    в URI.AllowedSchemes. По умолчанию этого нет — трекинг-пиксели
     *    через data:image тоже возможны, но только как изображение.
     *
     *  • Parsedown для ссылок использует href — это покрыто
     *    Блоком 2 и ограничено схемами в Блоке 5.
     *
     * Итог: любые опасные выражения, которые могут попасть в контент
     * (в том числе через «сырой» HTML, который Parsedown пробрасывает
     * без изменений) — вырезаются Блоками 2, 3, 4, 5, 6.
     * ---------------------------------------------------------------------- */
];