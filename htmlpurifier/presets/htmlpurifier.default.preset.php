<?php
/**
 * ============================================================================
 * HTML Purifier — пресет по умолчанию (fallback)
 * ============================================================================
 *
 * Файл:    plugins/htmlpurifier/presets/htmlpurifier.default.preset.php
 * Тип:     резервный пресет для всех групп без своего файла
 *          htmlpurifier.group_N.preset.php
 *
 * Задача:  пропустить безопасный HTML (жирный, курсив, списки, таблицы,
 *          ссылки, картинки) и при этом гарантированно вырезать всё, чем
 *          можно атаковать сайт или читателя — с учётом того, что
 *          контент парсится Parsedown (Markdown → HTML).
 *
 * Структура файла:
 *   • Блок 1 — оригинальные настройки (оставлены без изменений).
 *   • Блок 2 — ДОБАВЛЕНО: явный whitelist тегов (HTML.Allowed).
 *   • Блок 3 — ДОБАВЛЕНО: чёрный список тегов.
 *   • Блок 4 — ДОБАВЛЕНО: чёрный список атрибутов.
 *   • Блок 5 — ДОБАВЛЕНО: whitelist схем ссылок.
 *   • Блок 6 — ДОБАВЛЕНО: whitelist для <iframe>.
 *   • Блок 7 — ДОБАВЛЕНО: контроль атрибутов target/rel/id.
 *   • Блок 8 — ДОБАВЛЕНО: выключение Flash/Object/Embed.
 *   • Блок 9 — заметки по совместимости с Parsedown.
 *
 * ВАЖНО: пресет срабатывает только для полей, указанных в настройках
 * плагина: Админка → Плагины → HTML Purifier → «Поля для очистки»
 * (page_text, com_text, forums_post_text …).
