/**
 * ============================================================================
 * HTML Purifier — пресет для суперадминов (MainGroupId = 5)
 * ============================================================================
 *
 * Файл:    plugins/htmlpurifier/presets/htmlpurifier.group_5.preset.php
 * Задача:  дать администратору свободу верстки (врезки, центрирование,
 *          классы, id, встроенные видео), но закрыть реально опасные
 *          конструкции: XSS, авторедиректы, подмену вёрстки и форм.
 *
 * Структура файла:
 *   • Блок 1 — оригинальные настройки (оставлены без изменений).
 *   • Блок 2 — ДОБАВЛЕНО: чёрный список тегов.
 *   • Блок 3 — ДОБАВЛЕНО: чёрный список атрибутов.
 *   • Блок 4 — ДОБАВЛЕНО: whitelist схем ссылок.
 *   • Блок 5 — ДОБАВЛЕНО: whitelist для <iframe>.
 *   • Блок 6 — ДОБАВЛЕНО: выключение Flash/Object/Embed.
 *   • Блок 7 — итоговое предупреждение о Trusted = true.
 *
 * ВАЖНО: пресет срабатывает только для полей, указанных в
 * настройках плагина: Админка → Плагины → HTML Purifier →
 * «Поля для очистки» (page_text, com_text, forums_post_text …).
 *
 * @package    HTML Purifier
 * @subpackage Presets
 * @author     Cotonti Team
 * @copyright  (c) Cotonti Team
 * @license    https://github.com/Cotonti/Cotonti/blob/master/License.txt
