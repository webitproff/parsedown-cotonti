 */

defined('COT_CODE') or die('Wrong URL');

require_once Cot::$cfg['plugins_dir']
    . '/htmlpurifier/lib/standalone/HTMLPurifier/Filter/YouTube.php';

$htmlpurifier_preset = [

    /* ========================================================================
     * БЛОК 1. ОРИГИНАЛЬНЫЕ НАСТРОЙКИ — ОСТАВЛЕНЫ КАК ЕСТЬ
     * ========================================================================
     * Ниже — то, что было в файле изначально. Не меняем, чтобы не сломать
     * привычное поведение админского пресета.
     * ---------------------------------------------------------------------- */

    // === Автоформатирование ===
    'AutoFormat.AutoParagraph'                => false,
    'AutoFormat.DisplayLinkURI'               => false,
    'AutoFormat.Linkify'                      => false,
    'AutoFormat.RemoveEmpty.RemoveNbsp'       => false,
    'AutoFormat.RemoveEmpty'                  => true,
    'AutoFormat.RemoveSpansWithoutAttributes' => true,

    // === Пользовательские фильтры ===
    'Filter.Custom'                           => [],

    // === HTML и вывод ===
    // null = использовать политику HTML Purifier по умолчанию.
    'HTML.Allowed'                            => null,

    // Разрешить полноэкранный режим для встраиваемых объектов.
    'HTML.FlashAllowFullScreen'               => true,

    // Автоматически добавлять rel="nofollow" ко всем ссылкам.
    'HTML.Nofollow'                           => true,

    // Разрешить <object> и <embed> в «безопасном» режиме.
    'HTML.SafeObject'                         => true,
    'HTML.SafeEmbed'                          => true,

    // === Режим доверия ===
    // true — Purifier отключает почти все внутренние фильтры.
    // Админ может верстать врезки, ставить классы, id, кастомные теги.
    // Плата за свободу: <script>, on*-атрибуты и javascript:-схемы
    // сами по себе НЕ вырезаются — их закрываем вручную ниже.
    'HTML.Trusted'                            => true,

    // Оригинальный чёрный список — только <script>.
    // Расширяется в Блоке 2.
    'HTML.ForbiddenElements'                  => ['script'],

    // === Flash / YouTube ===
    'Output.FlashCompat'                      => true,
    'Filter.YouTube'                          => true,

    // === URI ===
    'URI.DisableExternal'                     => false,
    'URI.DisableExternalResources'            => false,

    // === Атрибуты ===
    'Attr.AllowedFrameTargets'                => ['_blank', '_self', '_parent', '_top'],

    // Разрешить id — нужен для якорей и внутренних ссылок #section.
    'Attr.EnableID'                           => true,


    /* ========================================================================
     * БЛОК 2. ДОБАВЛЕНО: ЧЁРНЫЙ СПИСОК ТЕГОВ
     * ========================================================================
     * Дополняем список ['script'] до полного набора опасных тегов.
     * Это перекрывает `HTML.ForbiddenElements` из Блока 1 — сработает
     * последняя присвоенная директива в массиве, то есть эта.
     *
     * Даже при Trusted = true эти теги будут удалены из контента.
     * ---------------------------------------------------------------------- */
    'HTML.ForbiddenElements'                  => [

        // Исполняемый код
        'script',

        // Подмена вёрстки сайта
        'style',        // <style>body{display:none}</style>
        'link',         // загрузка чужого CSS/JS
        'meta',         // <meta http-equiv="refresh"> — редирект
        'base',         // <base href="//evil.example"> — угон ссылок

        // Подмена форм (фишинг, CSRF)
        'form',
        'input',
        'textarea',
        'select',
        'option',
        'button',

        // Внешние встраивания — убираем ЛЮБЫЕ,
        // YouTube-плееры идут через <iframe> и разрешены отдельно
        // в Блоке 5 (HTML.SafeIframe + URI.SafeIframeRegexp).
        'object',
        'embed',
        'applet',

        // Небезопасный рендеринг
        'canvas',
        'svg',          // SVG умеет исполнять JS внутри себя
        'math',         // исторически использовался для XSS
    ],


    /* ========================================================================
     * БЛОК 3. ДОБАВЛЕНО: ЧЁРНЫЙ СПИСОК АТРИБУТОВ
     * ========================================================================
     * При Trusted = true Purifier пропускает onclick, onerror, onload
     * и прочие обработчики событий. Закрываем их вручную.
     *
     * '*@on*'   — любой атрибут, начинающийся с "on", у любого тега.
     *             Это onclick, onerror, onload, onmouseover, onfocus,
     *             onwheel, onanimationend и т.д. — сотни вариантов.
     * '*@formaction' — переопределение action формы.
     * '*@xmlns'      — ломает XHTML-парсинг.
     * '*@srcdoc'     — встраивание произвольного HTML в <iframe>.
     * 'a@ping'       — трекинг-пинг браузера при клике.
     * 'a@download'   — принудительное скачивание файла.
     * ---------------------------------------------------------------------- */
    'HTML.ForbiddenAttributes'                => [
        '*@on*',
        '*@formaction',
        '*@xmlns',
        '*@srcdoc',
        'a@ping',
        'a@download',
    ],


    /* ========================================================================
     * БЛОК 4. ДОБАВЛЕНО: WHITELIST СХЕМ ССЫЛОК
     * ========================================================================
     * При Trusted = true HTML Purifier перестаёт проверять схемы URL.
     * Значит, <a href="javascript:alert(1)">click</a> пройдёт.
     * Явный whitelist отсекает всё лишнее:
     *   http, https — обычные ссылки;
     *   mailto      — почта;
     *   tel         — телефоны.
     * Не проходят: javascript:, vbscript:, data:text/html, file:,
     *              chrome:, about: и любая другая экзотика.
     * ---------------------------------------------------------------------- */
    'URI.AllowedSchemes'                      => [
        'http'   => true,
        'https'  => true,
        'mailto' => true,
        'tel'    => true,
    ],


    /* ========================================================================
     * БЛОК 5. ДОБАВЛЕНО: WHITELIST ДЛЯ IFRAME
     * ========================================================================
     * Разрешаем <iframe> ТОЛЬКО из доверенных источников.
     * Всё остальное, включая <iframe src="/admin.php"> и
     * <iframe src="//evil.example">, будет удалено.
     * ---------------------------------------------------------------------- */
    'HTML.SafeIframe'                         => true,
    'URI.SafeIframeRegexp'                    => '%^(https?:)?//('
        . 'www\.youtube(?:-nocookie)?\.com/embed/|'
        . 'player\.vimeo\.com/video/|'
        . 'vk\.com/video_ext\.php'
        . ')%i',


    /* ========================================================================
     * БЛОК 6. ДОБАВЛЕНО: ВЫКЛЮЧЕНИЕ FLASH / OBJECT / EMBED
     * ========================================================================
     * При Trusted = true включённые SafeObject/SafeEmbed/FlashCompat
     * ослабляют защиту. Выключаем их — <object>, <embed>, <applet>
     * и так удаляются через Блок 2.
     * ---------------------------------------------------------------------- */
    'HTML.FlashAllowFullScreen'               => false,
    'HTML.SafeObject'                         => false,
    'HTML.SafeEmbed'                          => false,
    'Output.FlashCompat'                      => false,


    /* ========================================================================
     * БЛОК 7. ИТОГОВОЕ ПРЕДУПРЕЖДЕНИЕ
     * ========================================================================
     * Что осталось в файле сознательно ослабленным и почему:
     *
     *  • HTML.Trusted = true
     *      Нужно, чтобы админ мог верстать врезки (<div class="...">),
     *      задавать id для якорей, использовать <kbd>, <mark>, <details>,
     *      произвольные классы и стили в атрибуте style.
     *
     *      ВНИМАНИЕ: при Trusted = true защита работает только за счёт
     *      ручных чёрных списков (Блоки 2–3) и whitelist'ов (Блоки 4–5).
     *      Если хочешь максимально безопасный режим — поменяй на
     *      'HTML.Trusted' => false и задай явный HTML.Allowed.
     *
     *  • HTML.Allowed = null
     *      Значит, Purifier использует свою политику по умолчанию.
     *      Совместно с Trusted = true это очень широкий набор тегов —
     *      ограничения работают только через Блоки 2 и 3.
     *
     *  • HTML.Nofollow = true
     *      Принудительно добавляет rel="nofollow" ко всем внешним
     *      ссылкам. Не влияет на безопасность, но полезно для SEO.
     *
     *  • Attr.EnableID = true
     *      Разрешает id у элементов — нужно для якорей #section.
     *      Оставляем, потому что пресет только для админа.
     * ---------------------------------------------------------------------- */
];